// Основные праздники, когда утренний пост должен считаться выходным.
// Сейчас это выбранные вручную фиксированные даты: Новый год,
// Рождество, 8 марта, 31 декабря и Спасы.
// Переносы выходных по постановлениям правительства сюда специально не
// добавлены: они меняются каждый год, а фиксированные даты стабильны.

export const HOLIDAYS = {
  "01-01": "Новый год",
  "01-07": "Рождество",
  "03-08": "8 Марта",
  "05-01": "Праздник Весны и Труда",
  "05-09": "День Победы",
  "08-14": "Медовый Спас",
  "08-19": "Яблочный Спас",
  "08-29": "Ореховый Спас",
  "12-31": "31 декабря",
};

export function holidayName(localDate) {
  const mmdd = String(localDate || "").slice(5, 10);
  return HOLIDAYS[mmdd] || "";
}

export function isHoliday(localDate) {
  return Boolean(holidayName(localDate));
}
